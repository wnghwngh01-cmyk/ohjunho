import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={window:{},Uint8ClampedArray,Uint8Array};
vm.runInNewContext(fs.readFileSync(new URL('../js/avatar-frame.js',import.meta.url),'utf8'),context);
const {recolor}=context.window.HaruAvatarFrame,size=10,source=new Uint8ClampedArray(size*size*4),regions=new Uint8Array(size*size);
for(let i=0;i<source.length;i+=4)source.set([220,170,150,128],i);
for(let x=0;x<5;x++)regions[x]=x+1;
source.set([115,135,90,255],20);regions[5]=1;
const flower=recolor(source,regions,size,'blossom','sky','rainbow');
assert.equal(new Set(Array.from({length:5},(_,i)=>Array.from(flower.slice(i*4,i*4+3)).join(','))).size,5,'five flowers must have five distinct rainbow colors');
assert.deepEqual(flower.slice(20,24),source.slice(20,24),'green leaves must keep their source color');
const mask=new Uint8Array(size*size);for(let x=3;x<=7;x++)mask[20+x]=1;
const rose=recolor(source,mask,size,'crown','sky','rose'),lilac=recolor(source,mask,size,'crown','sky','lilac');
for(let p=0;p<mask.length;p++)if(!mask[p])assert.deepEqual(rose.slice(p*4,p*4+4),lilac.slice(p*4,p*4+4),'changing crown color must not recolor surrounding ring');
const accent=23*4;
assert.ok(Math.hypot(...[0,1,2].map(i=>rose[accent+i]-lilac[accent+i]))>40,'rose and lilac must remain visibly different');
const rainbow=recolor(source,mask,size,'crown','rainbow','rainbow');
assert.equal(new Set([3,4,5,6,7].map(x=>Array.from(rainbow.slice((20+x)*4,(20+x)*4+3)).join(','))).size,5,'crown rainbow must vary from left to right');
assert.notDeepEqual(rainbow.slice(0,3),rainbow.slice(90*4,90*4+3),'ring rainbow must vary vertically');
for(const result of [flower,rose,lilac,rainbow])for(let i=3;i<source.length;i+=4)assert.equal(result[i],source[i],'preserve transparency');
console.log('avatar-frame-color-behavior: PASS');
