import assert from 'node:assert/strict';
import fs from 'node:fs';
import {PGlite} from '@electric-sql/pglite';
import '../js/finance-utils.js';
const F=globalThis.HaruFinance;
const rows=[{tx_type:'expense',category:'식비',amount:150000,tx_date:'2026-10-01'},{tx_type:'expense',category:'쇼핑',amount:50000,tx_date:'2026-10-02'},{tx_type:'income',amount:900000,tx_date:'2026-10-03'},{tx_type:'balance',amount:5000000,tx_date:'2026-10-01'},{tx_type:'expense',category:'교통',amount:9000,tx_date:'2026-09-30'}];
const result=F.budgetSummary(rows,'2026-10',{'식비':300000,'교통':100000});
assert.ok(!F.budgetCategories(rows,'2026-10').includes('급여'),'income-only categories must not appear as expense budgets');
assert.ok(F.budgetCategories([{tx_type:'expense',category:'사용자 분류',tx_date:'2026-10-10'}],'2026-10').includes('사용자 분류'));
assert.equal(result.remaining,250000);assert.equal(result.expense,200000);assert.equal(result.unbudgeted,50000);assert.equal(result.income,900000);
const edited=rows.map((r,i)=>i===0?{...r,amount:180000}:r);
assert.equal(F.budgetSummary(edited,'2026-10',{'식비':300000}).remaining,120000);
assert.equal(F.budgetSummary(rows.slice(1),'2026-10',{'식비':300000}).remaining,300000);
assert.equal(F.budgetSummary(rows,'2026-11',{'식비':300000}).remaining,300000);
assert.equal(F.budgetSummary(rows,'2026-10',{'식비':0}).remaining,-150000);
assert.equal(F.budgetSummary(rows,'2026-10',{}).configured,false);
assert.equal(F.parseBudget(''),null);assert.equal(F.parseBudget('0'),0);assert.equal(F.parseBudget('123,456,789'),123456789);
for(const bad of ['-1','1.5','1e6','1,23','NaN','1000000000000'])assert.throws(()=>F.parseBudget(bad));

// Real PostgreSQL semantics in embedded PGlite, not a live Supabase test.
let db=new PGlite();
await db.exec(`create role anon;create role authenticated;create schema auth;create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
grant usage on schema auth to authenticated,anon;grant execute on function auth.uid() to authenticated,anon;
create function public.export_my_data() returns jsonb language sql as $$select jsonb_build_object('version',3,'profiles',jsonb_build_array(jsonb_build_object('id',auth.uid())))$$;
create function public.restore_my_data(p_backup jsonb) returns jsonb language plpgsql as $$begin if p_backup->'profiles'->0->>'id' is distinct from auth.uid()::text then raise exception 'wrong owner';end if;return jsonb_build_object('restored',0);end$$;
insert into auth.users values('00000000-0000-0000-0000-000000000001'),('00000000-0000-0000-0000-000000000002');`);
await db.exec(fs.readFileSync('supabase/step22_monthly_budgets.sql','utf8'));
const a='00000000-0000-0000-0000-000000000001',b='00000000-0000-0000-0000-000000000002';
async function login(id){await db.exec(`reset role;set test.uid='${id}';set role authenticated;`)}
const rpc=async(sql,args=[])=> (await db.query(sql,args)).rows[0].value;
const get=month=>rpc('select public.get_month_budget($1::date) value',[month]);
const save=(month,items,revision)=>rpc('select public.save_month_budget($1::date,$2::jsonb,$3::integer) value',[month,JSON.stringify(items),revision]);
await login(a);
assert.equal((await get('2026-01-01')).status,'none');
const initial=await save('2026-01-01',{'식비':300000,'교통':100000},0);
assert.equal(initial.status,'saved');
const feb=await get('2026-02-01');
// The initially sealed months before the first backdated save were unset;
// subsequent historical edits cannot rewrite those elapsed months.
assert.deepEqual(feb.items,{});
const current=(await db.query("select date_trunc('month',now() at time zone 'Asia/Seoul')::date::text m")).rows[0].m;
let now=await get(current);now=await save(current,{'식비':300000,'교통':100000},now.revision);
const next=(await db.query("select ($1::date+interval '1 month')::date::text m",[current])).rows[0].m;
assert.equal((await get(next)).status,'inherited');
assert.equal((await get(next)).items['식비'],300000);
assert.equal((await db.query('select count(*)::int n from finance_budget_months where month=$1',[next])).rows[0].n,0,'future read must not create rows');
const explicit=await save(next,{},0);assert.equal(explicit.status,'saved');assert.deepEqual((await get(next)).items,{});
await assert.rejects(()=>save(current,{'식비':1},now.revision-1),/다른 기기/);
await assert.rejects(()=>save(current,{'식비':-1},now.revision),/정수/);
await save(current,{'식비':0},now.revision);
assert.deepEqual((await get(next)).items,{},'explicit cleared future month survives earlier edit');
assert.deepEqual((await get('2026-01-01')).items,{'식비':300000,'교통':100000});
const backup=await rpc('select export_my_data() value');
assert.ok(backup.finance_budget_months.some(x=>x.month===next&&Object.keys(x.items).length===0));
await rpc('select restore_my_data($1::jsonb) value',[JSON.stringify(backup)]);
assert.deepEqual((await get(current)).items,{'식비':0});
// Seal an elapsed multi-month gap, then modify the earlier source. Stored
// snapshots including the year boundary must retain their original budgets.
await save('2098-12-01',{'교통':100000},0);
await db.exec(`reset role;select seal_budget_months('${a}','2098-12-01','2099-02-01');set role authenticated;`);
const december=await get('2098-12-01');
await save('2098-12-01',{'교통':200000},december.revision);
assert.equal((await get('2099-01-01')).items['교통'],100000);
assert.equal((await get('2099-02-01')).items['교통'],100000);
const invalidBackup={...backup,finance_budget_months:[{month:current,items:{'식비':88}},{month:next,items:{'교통':-1}}]};
await assert.rejects(()=>rpc('select restore_my_data($1::jsonb) value',[JSON.stringify(invalidBackup)]),/정수/);
assert.deepEqual((await get(current)).items,{'식비':0},'failed restore must roll back earlier restored months');
await db.exec('reset role');
const snapshot=await db.dumpDataDir();await db.close();db=new PGlite({loadDataDir:snapshot});
await login(a);
assert.deepEqual((await get(current)).items,{'식비':0},'persisted database reload must retain budget');
assert.equal((await get('2099-01-01')).items['교통'],100000);
await login(b);
assert.equal((await get(current)).status,'none');
assert.equal((await db.query('select * from finance_budget_months')).rows.length,0);
await assert.rejects(()=>db.exec(`insert into finance_budget_months(user_id,month) values('${a}','2099-01-01')`),/permission denied/);
await assert.rejects(()=>rpc('select restore_my_data($1::jsonb) value',[JSON.stringify(backup)]),/wrong owner/);
await db.exec('reset role;set role anon');
await assert.rejects(()=>get(current),/permission denied/);
await db.close();
console.log('monthly budgets: PASS (calculations, unset/zero, history, future preview, clearing, conflict, validation, backup, RLS)');
